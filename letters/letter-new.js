// responsive repositioning if window resize
window.addEventListener("resize", () => {
    envelopes.forEach((env, idx) => {
        if (!env.querySelector(".letter").style.opacity || env.querySelector(".letter").style.opacity === "0") {
            // only adjust if not opened (avoid conflict)
            if (!env._gsap || !env._gsap.isActive()) {
                gsap.set(env, {
                    x: 0,
                    y: 0
                });
                env.style.left = `${28 + (idx % 3) * 6}px`;
                env.style.top = `${100 + idx * 28}px`;
            }
        }
    });
});

// additional micro floating background stars dynamic
function createSparkle() {
    const spark = document.createElement('div');
    spark.style.position = 'fixed';
    spark.style.width = '2px';
    spark.style.height = '2px';
    spark.style.background = 'rgba(255,235,190,0.7)';
    spark.style.borderRadius = '50%';
    spark.style.pointerEvents = 'none';
    spark.style.left = Math.random() * 100 + '%';
    spark.style.top = Math.random() * 100 + '%';
    spark.style.opacity = Math.random() * 0.6 + 0.2;
    spark.style.zIndex = '1';
    document.body.appendChild(spark);
    gsap.to(spark, {
        duration: Math.random() * 6 + 4,
        opacity: 0,
        y: '-=30',
        onComplete: () => spark.remove()
    });
    setTimeout(createSparkle, 3000);
}
