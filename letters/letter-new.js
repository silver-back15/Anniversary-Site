const table = document.getElementById("table");
const envelopes = [];

// create rich letter content with HTML formatting (preserve linebreaks)
function formatLetterHTML(content) {
    const paragraphs = content.split(/\n\n/);
    let html = '';
    paragraphs.forEach(para => {
        if (para.trim().startsWith('With love,') || para.trim().startsWith('Yours,') || para.trim().startsWith('Your ') || para.match(/Juju|Jude|Joey/)) {
            html += `<div class="letter-signature">${para.replace(/\n/g, '<br>')}</div>`;
        } else {
            html += `<p>${para.replace(/\n/g, '<br>')}</p>`;
        }
    });
    return html;
}

LETTERS_RAW.forEach((content, idx) => {
    const env = document.createElement("div");
    env.className = "envelope";
    // stagger stack positions beautifully
    env.style.top = `${100 + idx * 28}px`;
    env.style.left = `${28 + (idx % 3) * 6}px`; // subtle offset
    env.style.zIndex = 10 + idx;

    // create wax seal element
    const sealDiv = document.createElement("div");
    sealDiv.className = "seal";

    env.innerHTML = `
<div class="front"></div>
<div class="flap"></div>
<div class="letter"></div>
`;
    const letterDiv = env.querySelector(".letter");
    // inject formatted content
    letterDiv.innerHTML = formatLetterHTML(content);
    env.appendChild(sealDiv);

    table.appendChild(env);

    const flap = env.querySelector(".flap");
    const letter = env.querySelector(".letter");

    const state = {
        open: false,
        animating: false
    };

    // open envelope with cinematic GSAP flow
    env.addEventListener("click", (e) => {
        e.stopPropagation();
        if (state.animating || state.open) return;
        state.animating = true;

        // subtle haptic scale feedback
        gsap.to(env, {
            duration: 0.2,
            scale: 0.98,
            yoyo: true,
            repeat: 1,
            ease: "power1"
        });

        // compute center x position (beautiful centering)
        const targetX = (window.innerWidth / 2) - (env.offsetWidth / 2) - 20;
        gsap.to(env, {
            duration: 0.9,
            x: targetX,
            y: -20,
            ease: "back.out(0.6)",
            onComplete: () => {
                gsap.to(flap, {
                    duration: 0.7,
                    rotateX: -175,
                    ease: "power2.inOut"
                });
                gsap.to(letter, {
                    duration: 1.1,
                    opacity: 1,
                    y: -70,
                    ease: "elastic.out(1, 0.5)",
                    onStart: () => {
                        letter.classList.add("glow-on-open");
                        setTimeout(() => letter.classList.remove("glow-on-open"), 900);
                    },
                    onComplete: () => {
                        state.open = true;
                        state.animating = false;
                        letter.style.pointerEvents = "auto";
                        // add subtle paper sound vibe (just visual enhancement)
                    }
                });
            }
        });
    });

    // close letter elegantly
    letter.addEventListener("click", (e) => {
        e.stopPropagation();
        if (state.animating || !state.open) return;
        state.animating = true;

        gsap.to(letter, {
            duration: 0.65,
            opacity: 0,
            y: 20,
            ease: "power2.in",
            onComplete: () => {
                letter.style.pointerEvents = "none";
                gsap.to(flap, {
                    duration: 0.6,
                    rotateX: 0,
                    ease: "back.out(0.8)"
                });
                gsap.to(env, {
                    duration: 0.9,
                    x: 40, // return to left stack
                    y: 0,
                    ease: "power3.inOut",
                    onComplete: () => {
                        state.open = false;
                        state.animating = false;
                        // reset tiny position variations for organic stack
                        env.style.left = `${28 + (idx % 3) * 6}px`;
                    }
                });
            }
        });
    });

    envelopes.push(env);
});

